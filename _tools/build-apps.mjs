#!/usr/bin/env node
// Builds the static app pages from _data/apps.json:
//   apps/index.html            list of apps
//   apps/<id>/index.html       one landing page per app
//   feedback/index.html        feedback form (posts to site.feedbackEndpoint)
//
// Usage:  node _tools/build-apps.mjs            (published apps only)
//         node _tools/build-apps.mjs --drafts   (also apps marked "draft": true, for local preview)
//         FEEDBACK_ENDPOINT=http://localhost:8787/feedback node _tools/build-apps.mjs --drafts
//
// Folders starting with "_" are not published by GitHub Pages (Jekyll), so this
// script and the data file stay out of the live site.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MARK = '<!-- generated by _tools/build-apps.mjs: edit _data/apps.json, not this file -->';
const includeDrafts = process.argv.includes('--drafts');

const data = JSON.parse(fs.readFileSync(path.join(ROOT, '_data/apps.json'), 'utf8'));
const site = data.site;
// FEEDBACK_ENDPOINT=http://localhost:8787/feedback overrides the endpoint for local testing.
site.feedbackEndpoint = process.env.FEEDBACK_ENDPOINT || site.feedbackEndpoint;
const apps = data.apps.filter((a) => includeDrafts || !a.draft);

for (const a of apps) {
  if (!/^[a-z0-9][a-z0-9-]{0,39}$/.test(a.id)) throw new Error(`Invalid app id "${a.id}" (use lowercase letters, digits, dashes)`);
}

const esc = (s = '') =>
  String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

function page({ title, description, canonical, head = '', body }) {
  return `<!DOCTYPE html>
${MARK}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<link rel="canonical" href="${esc(site.url + canonical)}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:url" content="${esc(site.url + canonical)}">
<link rel="icon" href="/favicon.ico">
<link rel="stylesheet" href="/apps/apps.css">
${head}</head>
<body>
<header class="topbar"><div class="wrap">
  <a class="brand" href="/apps/">${esc(site.name)}</a>
  <nav><a href="/apps/">Apps</a><a href="/feedback/">Feedback</a><a href="/">About</a></nav>
</div></header>
<main class="wrap">
${body}
</main>
<footer class="wrap foot">© ${new Date().getFullYear()} ${esc(site.name)} · <a href="/feedback/">Send feedback</a></footer>
</body>
</html>
`;
}

function icon(a, size = 'md') {
  if (a.icon) return `<img class="icon icon-${size}" src="${esc(a.icon)}" alt="" width="96" height="96">`;
  return `<span class="icon icon-${size} icon-fallback" aria-hidden="true">${esc(a.name.charAt(0))}</span>`;
}

function storeButtons(a) {
  const b = [];
  if (a.appStoreUrl) b.push(`<a class="btn" href="${esc(a.appStoreUrl)}" rel="noopener">App Store</a>`);
  if (a.googlePlayUrl) b.push(`<a class="btn" href="${esc(a.googlePlayUrl)}" rel="noopener">Google Play</a>`);
  return b.length ? `<div class="stores">${b.join('')}</div>` : '';
}

function platforms(a) {
  return [a.appStoreUrl && 'iOS', a.googlePlayUrl && 'Android'].filter(Boolean).join(' · ');
}

// ---------- apps/index.html ----------
const cards = apps
  .map(
    (a) => `<a class="card" href="/apps/${a.id}/">
  ${icon(a)}
  <span class="card-text"><strong>${esc(a.name)}</strong><span>${esc(a.tagline)}</span><small>${esc(platforms(a))}</small></span>
</a>`,
  )
  .join('\n');

const listHtml = page({
  title: site.name,
  description: site.tagline,
  canonical: '/apps/',
  body: `<section class="hero"><h1>${esc(site.name)}</h1><p>${esc(site.tagline)}</p></section>
<section class="grid">
${cards || '<p class="muted">New apps are on the way.</p>'}
</section>`,
});

// ---------- apps/<id>/index.html ----------
function appHtml(a) {
  const features = (a.features || []).map((f) => `<li>${esc(f)}</li>`).join('');
  const shots = (a.screenshots || []).map((s) => `<img src="${esc(s)}" alt="${esc(a.name)} screenshot" loading="lazy">`).join('');
  const links = [
    a.privacyUrl && `<a href="${esc(a.privacyUrl)}">Privacy policy</a>`,
    a.termsUrl && `<a href="${esc(a.termsUrl)}">Terms</a>`,
    `<a href="/feedback/?app=${a.id}">Send feedback</a>`,
  ]
    .filter(Boolean)
    .join('');
  return page({
    title: `${a.name}: ${a.tagline}`,
    description: a.description || a.tagline,
    canonical: `/apps/${a.id}/`,
    head: a.appStoreId ? `<meta name="apple-itunes-app" content="app-id=${esc(a.appStoreId)}">\n` : '',
    body: `<section class="app-hero">
  ${icon(a, 'lg')}
  <div><h1>${esc(a.name)}</h1><p class="lead">${esc(a.tagline)}</p>${storeButtons(a)}</div>
</section>
${a.description ? `<p class="desc">${esc(a.description)}</p>` : ''}
${features ? `<ul class="features">${features}</ul>` : ''}
${shots ? `<div class="shots">${shots}</div>` : ''}
<p class="links">${links}</p>`,
  });
}

// ---------- feedback/index.html ----------
const options = apps.map((a) => `<option value="${a.id}">${esc(a.name)}</option>`).join('');
const feedbackHtml = page({
  title: `Feedback · ${site.name}`,
  description: `Tell us what to fix or build next in ${site.name}.`,
  canonical: '/feedback/',
  body: `<section class="hero"><h1>Send feedback</h1><p>Bug, idea or just a thought. Every message is read.</p></section>
<form id="fb" class="form" novalidate>
  <label>App
    <select name="app" required><option value="">Choose an app</option>${options}<option value="general">Something else</option></select>
  </label>
  <fieldset class="rating"><legend>How do you like it? <span class="muted">(optional)</span></legend>
    <div class="stars">${[5, 4, 3, 2, 1].map((n) => `<input type="radio" id="r${n}" name="rating" value="${n}"><label for="r${n}" title="${n} star${n > 1 ? 's' : ''}">★</label>`).join('')}</div>
  </fieldset>
  <label>Your feedback
    <textarea name="message" rows="6" maxlength="5000" required placeholder="What happened, or what would make the app better?"></textarea>
  </label>
  <label><span>Email or other contact <span class="muted">(optional)</span></span>
    <input name="contact" maxlength="200" autocomplete="email">
  </label>
  <label class="check"><input type="checkbox" name="contactConsent"> You may contact me about this feedback</label>
  <div class="hp" aria-hidden="true"><label>Website <input name="website" tabindex="-1" autocomplete="off"></label></div>
  <button class="btn" type="submit">Send</button>
  <p class="status" role="status" aria-live="polite"></p>
</form>
<div id="thanks" class="thanks" hidden><h2>Thank you!</h2><p>Your feedback was sent.</p><p><a href="/apps/">Back to apps</a></p></div>
<script>
(function () {
  var ENDPOINT = ${JSON.stringify(site.feedbackEndpoint || '')};
  var form = document.getElementById('fb');
  var status = form.querySelector('.status');
  var started = Date.now();
  var q = new URLSearchParams(location.search);
  var meta = { version: q.get('v') || '', os: q.get('os') || '' };
  var src = q.get('source');
  if (q.get('app')) form.app.value = q.get('app');
  if (!ENDPOINT) { status.textContent = 'Feedback is not set up yet. Please try again later.'; form.querySelector('button').disabled = true; }

  form.addEventListener('submit', function (e) {
    e.preventDefault();
    if (!form.app.value) { status.textContent = 'Please choose an app.'; form.app.focus(); return; }
    if (form.message.value.trim().length < 3) { status.textContent = 'Please write a little more.'; form.message.focus(); return; }
    var rating = form.querySelector('input[name=rating]:checked');
    var body = {
      app: form.app.value, source: ['ios', 'android'].indexOf(src) >= 0 ? src : 'web',
      rating: rating ? Number(rating.value) : null, message: form.message.value,
      contact: form.contact.value, contactConsent: form.contactConsent.checked,
      website: form.website.value, elapsedMs: Date.now() - started,
      version: meta.version, os: meta.os, page: document.referrer.slice(0, 300)
    };
    var btn = form.querySelector('button');
    btn.disabled = true; status.textContent = 'Sending…';
    fetch(ENDPOINT, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
      .then(function (r) { return r.json().catch(function () { return {}; }).then(function (j) { if (!r.ok || !j.ok) throw new Error(j.error || r.status); }); })
      .then(function () { form.hidden = true; document.getElementById('thanks').hidden = false; })
      .catch(function () { status.textContent = 'Could not send. Please check your connection and try again.'; btn.disabled = false; });
  });
})();
</script>`,
});

// ---------- write ----------
function write(rel, html) {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html);
  console.log('wrote', rel);
}

write('apps/index.html', listHtml);
for (const a of apps) write(`apps/${a.id}/index.html`, appHtml(a));
write('feedback/index.html', feedbackHtml);

// Remove pages of apps that were deleted or turned back into drafts (only ones this script generated).
const keep = new Set(apps.map((a) => a.id));
for (const d of fs.readdirSync(path.join(ROOT, 'apps'), { withFileTypes: true })) {
  if (!d.isDirectory() || keep.has(d.name)) continue;
  const f = path.join(ROOT, 'apps', d.name, 'index.html');
  if (fs.existsSync(f) && fs.readFileSync(f, 'utf8').includes(MARK)) {
    fs.rmSync(f);
    if (fs.readdirSync(path.dirname(f)).length === 0) fs.rmdirSync(path.dirname(f));
    console.log('removed', `apps/${d.name}/index.html`);
  }
}
if (!site.feedbackEndpoint) console.warn('note: site.feedbackEndpoint is empty, the feedback form shows "not set up yet"');
